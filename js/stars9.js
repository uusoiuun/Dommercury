/** Пара хэ-ту между двумя секторами (в любом порядке) или null. */
export function heTuMatch(x, y) {
  return HETU.find((c) => (x[c.kind] === c.a && y[c.kind] === c.b) || (x[c.kind] === c.b && y[c.kind] === c.a)) || null;
}

/** Комбинации хэ-ту между соседними секторами плана (общая сторона). */
export function heTuPairs(layout, palaces) {
  const combos = HETU;
  const cells = [];
  layout.forEach((r, i) => r.forEach((lo, j) => cells.push({ lo, i, j })));
  const out = [];
  for (const c of combos) {
    for (const x of cells) {
      for (const y of cells) {
        const adjacent = Math.abs(x.i - y.i) + Math.abs(x.j - y.j) === 1;
        if (!adjacent || x.lo === 5 || y.lo === 5) continue;
        if (palaces[x.lo][c.kind] === c.a && palaces[y.lo][c.kind] === c.b) out.push({ ...c, from: x.lo, to: y.lo });
      }
    }
  }
  return out;
}

/**
 * Секрет двухэтажного дома: сектор с горной 9 и водной 9 —
 * вход на первом этаже (водная 9), спальня над ним на втором (горная 9).
 */
export function doubleNine(palaces) {
  const lo = Object.keys(palaces).map(Number).find((k) => k !== 5 && palaces[k].mountain === 9 && palaces[k].water === 9);
  return lo ?? null;
}

// ---- Пять элементов: какая звезда «нападает» на число Гуа ----

const ELEMENT = { 1: 'вода', 2: 'земля', 3: 'дерево', 4: 'дерево', 5: 'земля', 6: 'металл', 7: 'металл', 8: 'земля', 9: 'огонь' };
// Цикл подавления: дерево → земля → вода → огонь → металл → дерево
const CONTROLS = { дерево: 'земля', земля: 'вода', вода: 'огонь', огонь: 'металл', металл: 'дерево' };

export const elementOf = (n) => ELEMENT[n];

/** Звезда подавляет элемент Гуа (например, горная 8 — земля — подавляет воду Гуа 1). */
export function attacksGua(star, gua) {
  return CONTROLS[ELEMENT[star]] === ELEMENT[gua];
}

