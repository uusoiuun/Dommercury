// Неблагоприятные водные звёзды 9-го периода: их лучше «смыть» в санузле или запереть в кладовке
export const UNFAVORABLE_WATER = [2, 3, 4, 5, 7];
// Неблагоприятные горные звёзды: их можно отдать кладовке, санузлу или активной зоне — там никто не спит
export const UNFAVORABLE_MOUNTAIN = [2, 3, 4, 5, 7];
// Благоприятные водные звёзды: санузел и кладовка их «смывают»
const GOOD_WATER = [9, 1, 8];

/**
 * Насколько помещение подходит сектору: 'good' | 'ok' | 'fix' | 'bad',
 * 'na' — звезда описана, но про это помещение не сказано, null — описания звезды нет.
 */
export function roomFit(room, mountain, water) {
  const r = ROOMS.find((x) => x.key === room);
  const star = r.by === 'mountain' ? MOUNTAIN[mountain] : WATER[water];
  if (!star) return null;
  // Санузел в горной 9 — плохо по описанию горной 9
  if (room === 'utility' && MOUNTAIN[mountain]?.noUtility) return 'bad';
  if (room === 'utility' && !GOOD_WATER.includes(water)) {
    if (UNFAVORABLE_WATER.includes(water) || UNFAVORABLE_MOUNTAIN.includes(mountain)) return 'good';
    // Водная 6 — приемлемая, санузел там нейтрален
    if (water === 6) return 'ok';
  }
  const fit = star.rooms[room] ?? 'na';
  // Спальня в водной 9 — плохо по описанию водной 9
  if (room === 'sleep' && WATER[water]?.noSleep && fit !== 'bad') return 'fix';
  return fit;
}

/** Где спать человеку с данным Гуа: сектора (номера Ло Шу) с уровнем. */
export function bedroomsFor(gua, palaces) {
  const out = [];
  for (const [lo, p] of Object.entries(palaces)) {
    if (Number(lo) === 5) continue;
    const m = p.mountain;
    let level = null;
    if (m === 9 || m === 1) level = 'good';
    else if (MOUNTAIN[m]?.rooms.sleep === 'bad') level = null;
    else if (MOUNTAIN[m]?.sleepGua?.includes(gua)) level = 'ok';
    if (level && WATER[p.water]?.noSleep) level = 'fix';
    if (level) out.push({ lo: Number(lo), level, mountain: m });
  }
  const rank = { good: 0, ok: 1, fix: 2 };
  // Сначала лучшие, при равенстве горная 9 раньше остальных
  return out.sort((a, b) => rank[a.level] - rank[b.level] || (a.mountain === 9 ? 0 : 1) - (b.mountain === 9 ? 0 : 1));
}

